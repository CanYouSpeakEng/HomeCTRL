"""
setup_device.py - One-Time Device Setup & Tuya Local Key Extractor.

This script helps configure your BARDI smart lamp for local control.
It can:
  1. Run the tinytuya cloud wizard to automatically extract your Device ID,
     Local Key, and local IP address from the Tuya Developer Platform.
  2. Perform a direct Cloud API query using your API Key & Secret.
  3. Let you enter your device details manually.

IMPORTANT NOTE:
The local key is an encryption secret tied to each SmartLife pairing session.
If you ever re-pair or reset your lamp in SmartLife, Tuya will issue a NEW local
key, and you will need to re-run this setup script.
"""

import os
import sys
import json

try:
    import tinytuya
    import tinytuya.wizard
except ImportError:
    print("\n[ERROR] tinytuya is not installed.")
    print("Please activate your virtual environment and run:")
    print("  pip install -r requirements.txt\n")
    sys.exit(1)

CONFIG_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "config.json")


def print_banner():
    print("=" * 68)
    print("        HomeCTRL - BARDI Smart Lamp Local Setup Wizard")
    print("=" * 68)
    print(
        "\nTo control your lamp locally over Wi-Fi without cloud delay,\n"
        "tinytuya needs your lamp's 'Local Key' (a 16-character encryption key).\n"
    )
    print("TUYA DEVELOPER CREDENTIALS REMINDER:")
    print(" - API Key / Access ID   (from project Overview tab)")
    print(" - API Secret            (from project Overview tab)")
    print(" - Region                (use 'us' for Western America / Indonesia)")
    print(" - Device ID             (Virtual ID from project Devices tab or SmartLife)")
    print("-" * 68)
    print("REMINDER ABOUT RE-PAIRING:")
    print(" - Your 'Local Key' changes whenever the lamp is re-paired in SmartLife.")
    print(" - If you re-pair the lamp, simply run this setup script again.")
    print("-" * 68)
    print("ROUTER DHCP RESERVATION:")
    print(" - To ensure your lamp's local IP never changes, assign a static lease")
    print("   (DHCP Reservation) in your Wi-Fi router settings for the lamp's MAC address.")
    print("=" * 68)


def run_cloud_wizard():
    """Runs tinytuya's official interactive wizard."""
    print("\nStarting the tinytuya setup wizard...")
    print("Follow the on-screen prompts from tinytuya.\n")

    try:
        tinytuya.wizard.wizard()
    except Exception as e:
        print(f"\n[ERROR] Wizard encountered an error: {e}")
        return

    import_devices_from_file()


def run_direct_cloud_fetch():
    """Directly queries the Tuya Cloud API using credentials."""
    print("\n--- Direct Tuya Cloud Fetch ---")
    api_key = input("API Key / Access ID: ").strip()
    api_secret = input("API Secret: ").strip()
    region = input("Region [us]: ").strip().lower() or "us"
    device_id = input("Device ID (Virtual ID of your lamp): ").strip()

    if not api_key or not api_secret or not device_id:
        print("\n[ERROR] API Key, Secret, and Device ID are all required.")
        return

    print("\nConnecting to Tuya Cloud...")
    try:
        cloud = tinytuya.Cloud(
            apiRegion=region,
            apiKey=api_key,
            apiSecret=api_secret,
            apiDeviceID=device_id,
        )
        devs = cloud.getdevices()
        if not devs or not isinstance(devs, list):
            print(f"\n[ERROR] Failed to fetch devices. Cloud response: {devs}")
            print("Tip: Ensure 'IoT Core' and 'Smart Home Device System' are authorized in Service API.")
            return

        print(f"\nFound {len(devs)} device(s) on your account!")
        
        # Scan local network for IP addresses
        print("Scanning local Wi-Fi to locate lamp IP address...")
        local_scan = {}
        try:
            local_scan = tinytuya.deviceScan(False, 5)
        except Exception:
            pass

        saved_devices = []
        for d in devs:
            dev_id = d.get("id", "")
            ip = ""
            if dev_id in local_scan:
                ip = local_scan[dev_id].get("ip", "")

            saved_devices.append({
                "name": d.get("name", "BARDI Smart Lamp"),
                "device_id": dev_id,
                "local_key": d.get("key", ""),
                "ip_address": ip or d.get("ip", ""),
                "protocol_version": str(d.get("version", "3.3")),
                "device_type": "lamp",
            })

        save_config(saved_devices)

    except Exception as e:
        print(f"\n[ERROR] Cloud query failed: {e}")


def import_devices_from_file():
    """Imports devices from devices.json generated by tinytuya wizard."""
    devices_file = "devices.json"
    if not os.path.exists(devices_file):
        print(f"\n[WARNING] '{devices_file}' was not found. Please verify credentials.")
        return

    try:
        with open(devices_file, "r", encoding="utf-8") as f:
            raw_devices = json.load(f)

        devices_list = []
        if isinstance(raw_devices, list):
            items = raw_devices
        elif isinstance(raw_devices, dict):
            items = raw_devices.values()
        else:
            items = []

        for item in items:
            devices_list.append({
                "name": item.get("name", "BARDI Smart Lamp"),
                "device_id": item.get("id", ""),
                "local_key": item.get("key", ""),
                "ip_address": item.get("ip", ""),
                "protocol_version": str(item.get("version", "3.3")),
                "device_type": "lamp",
            })

        if devices_list:
            save_config(devices_list)
        else:
            print("\n[INFO] No devices found in devices.json.")
    except Exception as e:
        print(f"\n[ERROR] Failed to read '{devices_file}': {e}")


def run_manual_setup():
    """Allows manual entry of device details."""
    print("\n--- Manual Configuration ---")
    name = input("Device Name [BARDI Smart Lamp]: ").strip() or "BARDI Smart Lamp"
    device_id = input("Device ID: ").strip()
    local_key = input("Local Key (16 characters): ").strip()
    ip_address = input("Lamp Local IP Address (e.g. 192.168.1.100): ").strip()
    protocol_version = input("Protocol Version [3.3]: ").strip() or "3.3"

    if not device_id or not local_key or not ip_address:
        print("\n[WARNING] Device ID, Local Key, or IP Address was left empty.")
        save_anyway = input("Save to config.json anyway? (y/N): ").strip().lower()
        if save_anyway not in ("y", "yes"):
            print("Setup cancelled.")
            return

    new_device = {
        "name": name,
        "device_id": device_id,
        "local_key": local_key,
        "ip_address": ip_address,
        "protocol_version": protocol_version,
        "device_type": "lamp",
    }
    save_config([new_device])


def save_config(devices: list):
    """Saves device list into config.json."""
    data = {"devices": devices}
    try:
        with open(CONFIG_PATH, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        print(f"\n[SUCCESS] Successfully saved {len(devices)} device(s) to config.json!")
        for d in devices:
            key_preview = d['local_key'][:4] + "************" if d['local_key'] else "NOT SET"
            print(f" - {d['name']} | ID: {d['device_id']} | IP: {d['ip_address'] or 'Needs IP'} | Key: {key_preview}")
        print("\nYou can now run 'python main.py' to control your lamp locally!")
    except Exception as e:
        print(f"\n[ERROR] Failed to save config.json: {e}")


def set_device_ip():
    """Allows quickly updating the IP address of an existing device in config.json."""
    if not os.path.exists(CONFIG_PATH):
        print("\n[ERROR] config.json does not exist. Run wizard or manual setup first.")
        return

    try:
        with open(CONFIG_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        devices = data.get("devices", [])
        if not devices:
            print("\n[ERROR] No devices found in config.json.")
            return

        print("\nExisting devices in config.json:")
        for idx, d in enumerate(devices, 1):
            ip_str = d.get("ip_address") or "No IP set"
            print(f" {idx}. {d.get('name')} (Current IP: {ip_str})")

        choice = input(f"\nSelect device number [1-{len(devices)}]: ").strip()
        if not choice.isdigit() or not (1 <= int(choice) <= len(devices)):
            print("Invalid selection.")
            return

        selected = devices[int(choice) - 1]
        new_ip = input(f"Enter local Wi-Fi IP address for '{selected.get('name')}' (e.g. 192.168.68.xxx): ").strip()
        if not new_ip:
            print("No IP entered. Cancelled.")
            return

        selected["ip_address"] = new_ip
        with open(CONFIG_PATH, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)

        print(f"\n[SUCCESS] Updated IP for '{selected.get('name')}' to {new_ip}!")
        print("You can now run 'python main.py' to control the lamp!")
    except Exception as e:
        print(f"\n[ERROR] Failed to update IP: {e}")


def main():
    print_banner()
    print("\nSelect setup option:")
    print(" 1. Run Guided Tuya Wizard (recommended - scans cloud & Wi-Fi)")
    print(" 2. Direct Cloud Fetch (enter Key & Secret directly)")
    print(" 3. Set/Update IP Address for an existing device (Quick)")
    print(" 4. Enter Device Details Manually")
    print(" 5. Exit")

    choice = input("\nEnter choice [1-5]: ").strip()
    if choice == "1":
        run_cloud_wizard()
    elif choice == "2":
        run_direct_cloud_fetch()
    elif choice == "3":
        set_device_ip()
    elif choice == "4":
        run_manual_setup()
    else:
        print("\nExiting setup. No changes made.")


if __name__ == "__main__":
    main()

